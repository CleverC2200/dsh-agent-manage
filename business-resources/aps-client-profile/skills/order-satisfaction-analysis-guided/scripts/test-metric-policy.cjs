const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),os=require('node:os');
const C=require('./report-core.js'),generate=require('./generate-report.cjs');
const base={title:'口径契约测试',scope:{object:'测试',period:'测试期间',cutoff:'测试截止',unit:'件',productionUnit:'件',mock:true},metric:{need:1000,shipped:500,rawShipped:1100,rate:0.73,monthlyShortage:500,demandChangeShortage:200,inPlanShortage:300,classificationComplete:true},method:'测试口径快照',findings:[]};
const missingPlan={...base,orderRowsComplete:true,orderRows:[{key:'1',finalPlan:null,totalOrder:1000,totalShipped:1100}]};
assert.equal(C.normalize(missingPlan).metric.demandChangeShortage,200);
assert.equal(C.rate(C.normalize(base)),'73.00%');
assert.equal(C.actualShipped(base),1100);
assert.equal(C.actualShipped({metric:{shipped:500}}),null);
assert.equal(C.actualShipped({metric:{shipped:500,shippedIsActual:true}}),500);
assert.equal(C.actualShipped({metric:{rawShipped:null,shipped:500,shippedIsActual:true}}),null);
assert.equal(C.rate({metric:{need:100,shipped:80}}),'—');
assert.equal(C.rate({metric:{need:100,shipped:80},calculation:{rate:'ratio-v1'}}),'80.00%');
assert.equal(C.rate({metric:{need:100,shipped:80,rate:null},calculation:{rate:'ratio-v1'}}),'—');
const legacy={...base,metric:{need:10,shipped:5},calculation:{classification:'legacy-minmax-v1'},orderRowsComplete:true,orderRows:[{key:'x',finalPlan:8,totalOrder:10,totalShipped:5}]};
assert.equal(C.normalize(legacy).metric.demandChangeShortage,2);
assert.throws(()=>C.normalize({...legacy,orderRowsComplete:false}));
assert.throws(()=>C.normalize({...base,metric:{...base.metric,inPlanShortage:1}}));
const sparse={...base,metric:{need:null,shipped:null,rate:null},demandRows:[],planRows:[]};
const out=fs.mkdtempSync(path.join(os.tmpdir(),'metric-policy-'));
generate(sparse,out);
const html=fs.readFileSync(path.join(out,'订单满足率原因分析报告.html'),'utf8');
const visibleHtml=html.replace(/<script[\s\S]*?<\/script>/g,'');
assert(!visibleHtml.includes('MIN(MAX('));
assert(!visibleHtml.includes('下月需求÷30'));
const {JSDOM}=require('./report-environment.cjs').resolveDOM().module;
const leaf={object:'省',reported:90,ordered:80,salesDemandPlanVariance:37,gap:5,unit:'件'};
const fixture={...base,demandRows:[{view:'品类经理',object:'品类',gap:5,children:[{object:'区',children:[leaf]}]}]};
fixture.planRows=[{object:'生产基地',scopeKey:'base',planned:100,actual:80,gap:37,rate:0.42,unit:'件'}];
generate(fixture,out);
fs.writeFileSync(path.join(out,'report-data.json'),JSON.stringify(fixture));
const dom=new JSDOM(fs.readFileSync(path.join(out,'订单满足率原因分析报告.html'),'utf8'),{runScripts:'dangerously'});
dom.window.document.querySelector('[data-view="product"]').click();
assert(dom.window.document.querySelector('[data-template-row]').textContent.includes('37'));
assert.equal(dom.window.document.querySelectorAll('.metric-value')[4].textContent,'73.00%');
dom.window.document.querySelector('[data-cause="plan"]').click();
const supply=dom.window.document.querySelectorAll('#specificAnalysis > .analysis-kpis > .analysis-kpi');
assert(supply[2].textContent.includes('37'));
assert(supply[3].textContent.includes('42.00%'));
dom.window.close();
console.log('Metric policy: PASS (published, opt-in legacy, null, sparse dimensions, DOM binding)');
console.log('Fixture directory: '+out);
const run=require('node:child_process').spawnSync(process.execPath,[path.join(__dirname,'test-report.cjs'),path.join(out,'订单满足率原因分析报告.html')],{stdio:'inherit',env:process.env});
if(run.status!==0)process.exitCode=run.status||1;
